#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate the human-readable copy doc from content.py. One source, no drift."""
import content as C, os

L = []
w = L.append
w(f"# {C.TITLE.upper()}")
w(f"## {C.SUBTITLE}")
w("### Copy source of truth | generated from build/content.py")
w("")
w("Do not edit this file. Edit `build/content.py` and run `python3 export_copy.py`.")
w("The PDF renders from the same file, so the copy and the artwork can never drift apart.")
w("")
w("---")
w("")
w("## COVER")
w("")
w(f"Eyebrow: {C.EYEBROW}")
w(f"Title: {C.TITLE}")
w("Strip: SIXTEEN COSTUMES · ONE LOOP")
w(f"Subtitle: {C.SUBTITLE}")
w(f"Standfirst: {C.COVER_STANDFIRST}")
w(f"Footer: {C.CLOSING_LINE} · {C.FOOTER_BRAND}")
w("")
w("---")
w("")
w(f"## {C.INTRO_TITLE.upper()}")
w("")
for p in C.INTRO:
    w(p); w("")
w("---")
w("")
w("## THE SIXTEEN")
w("")
for d in C.CODES:
    w(f"### {d['n']} · {d['name']}")
    w("")
    w(f"**The moment.** {d['moment']}")
    w("")
    w(f"**You have been calling it.** {d['disguise']}")
    w("")
    w(f"**What it actually is.** {d['truth']}")
    w("")
    w(f"**The loop.** {d['loop']}")
    w("")
    if d.get("note"):
        w(f"**Lived proof.** {d['note']}")
        w("")
    w(f"**And this is what it is called.** {d['name']}")
    w("")
    w(f"**The question.** {d['question']}")
    w("")
    w("---")
    w("")
w(f"## {C.SCAN_TITLE.upper()}")
w("")
for p in C.SCAN_INTRO: w(p); w("")
w("[ tick grid 01 to 16 ]")
w("")
for p in C.SCAN_MID: w(p); w("")
w("[ three ruled lines ]")
w("")
w(C.SCAN_COUNT); w("")
w("**The clusters.**"); w("")
for nm, nums in C.CLUSTERS:
    w(f"- {nm} · {nums}")
w("")
w(C.SCAN_CLOSE); w("")
w("---"); w("")
w(f"## {C.CTA_TITLE.upper()}")
w("")
for p in C.CTA_BODY: w(p); w("")
w(f"**Button.** {C.CTA_BUTTON}")
w(f"**Link.** {C.CTA_URL}")
w("")
for p in C.CTA_CLOSE: w(p); w("")
w(C.SIGN_OFF); w("")
w(C.SIGN_OFF_PS); w("")
w("---"); w("")
w(f"*{C.CLOSING_LINE.title()}*")

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "content",
                   "sixteen-copy.md")
open(out, "w", encoding="utf-8").write("\n".join(L) + "\n")
print("wrote", os.path.normpath(out))
